"""QA de layout, autenticação interceptada; nenhum CORE ou progresso reais."""
import argparse
import json
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

parser = argparse.ArgumentParser()
parser.add_argument('--base-url', default='http://127.0.0.1:4180')
parser.add_argument('--report', default='tests/responsivo-qa.json')
args = parser.parse_args()
report = Path(args.report)
report.parent.mkdir(parents=True, exist_ok=True)
results, blocked, errors = [], [], []
with sync_playwright() as p:
    browser = p.chromium.launch(executable_path='/opt/playwright/chromium-1243/chrome-linux64/chrome', headless=True, args=['--no-sandbox'])
    for width, height in [(1093, 550), (1280, 620), (1366, 650), (1536, 754), (1920, 950)]:
        context = browser.new_context(viewport={'width': width, 'height': height}, service_workers='block')
        def api(route):
            r = route.request
            if '/api/auth/me' in r.url and r.method == 'GET':
                return route.fulfill(json={'usuario': {'id': 987654, 'nome': 'Professor Gabriel', 'login': 'qa-layout', 'papel': 'professor', 'primeiro_acesso': False, 'trocar_senha': False}})
            blocked.append({'method': r.method, 'url': r.url})
            route.fulfill(status=503, json={'sucesso': False, 'mensagem': 'Bloqueado pelo ensaio de layout'})
        context.route('**/api/**', api)
        page = context.new_page()
        page.on('pageerror', lambda e: errors.append(str(e)))
        page.goto(args.base_url + '/laboratorio/previa-responsiva')
        if page.get_by_role('button', name='Pular apresentação').is_visible():
            page.get_by_role('button', name='Pular apresentação').click()
        expect(page.get_by_text('PRÉVIA DE LAYOUT', exact=True)).to_be_visible(timeout=3500)
        expect(page.get_by_text('Dados demonstrativos. Não inicia CORE nem altera seu progresso.', exact=True)).to_be_visible()
        expect(page.get_by_label('Comando do terminal')).to_be_enabled()
        faixa = page.locator('.previa-progresso-integrado')
        expect(faixa).to_be_visible()
        expect(faixa).to_be_in_viewport(ratio=1)
        expect(faixa).to_contain_text('0 de 3 etapas')
        expect(page.locator('.lab-progresso-painel')).to_have_count(0)
        page.get_by_label('Comando do terminal').fill('rascunho ao consultar etapas')
        page.get_by_role('button', name='Ver etapas', exact=True).click()
        expect(page.get_by_role('dialog', name='Etapas da missão')).to_be_visible()
        page.get_by_role('button', name='Fechar etapas', exact=True).click()
        page.get_by_role('button', name='Conversar com o Link', exact=True).click()
        expect(page.get_by_role('heading', name='Vamos descobrir juntos?')).to_be_visible()
        page.get_by_role('button', name='Minimizar conversa com o Link').click()
        expect(page.locator('.lab-missao-painel.fechado')).to_have_count(0)
        expect(page.get_by_label('Comando do terminal')).to_have_value('rascunho ao consultar etapas')
        page.get_by_label('Comando do terminal').fill('')
        expect(page.get_by_label('Comando do terminal')).to_be_in_viewport(ratio=1, timeout=3000)
        expect(page.get_by_role('button', name='Executar', exact=True)).to_be_in_viewport(ratio=1)
        assert page.evaluate('window.visualViewport.scale') == 1
        assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'), 'Rolagem horizontal'
        output = page.locator('.lab-previa .lab-terminal-saida')
        if output.bounding_box()['height'] < (150 if height < 600 else 200):
            print('DIAGNOSTICO_ALTURA', page.evaluate('''() => Object.fromEntries(['.topbar','.previa-layout-aviso','.previa-layout-controles','.lab-cabecalho','.previa-faixa-missao','.previa-progresso-integrado','.previa-progresso-linha','.previa-etapa-integrada','.previa-progresso-inferior','.previa-topologia-centro','.previa-ajuda-integrada'].map(s=>{const e=document.querySelector(s); const r=e.getBoundingClientRect(); const c=getComputedStyle(e);return [s,{y:r.y,h:r.height,w:r.width,p:c.padding,lh:c.lineHeight,grid:c.gridTemplateColumns}]}))'''))
        assert output.bounding_box()['height'] >= (150 if height < 600 else 200), output.bounding_box()
        page.screenshot(path=str(report.with_suffix(f'.inicial-{width}x{height}.png')), full_page=True)
        command = page.get_by_label('Comando do terminal')
        command.fill('rascunho preservado')
        page.get_by_role('button', name='Ocultar Bastidores', exact=True).click()
        expect(command).to_have_value('rascunho preservado')
        page.get_by_role('button', name='Mostrar Bastidores', exact=True).click()
        expect(command).to_have_value('rascunho preservado')
        menu = page.get_by_role('button', name='Recolher menu', exact=True)
        if menu.count(): menu.click()
        else: page.get_by_role('button', name='Abrir menu', exact=True).first.click()
        expect(command).to_have_value('rascunho preservado')
        page.evaluate('window.scrollTo(0, 0)')
        expect(command).to_be_in_viewport(ratio=1)
        expect(page.get_by_role('button', name='Executar', exact=True)).to_be_in_viewport(ratio=1)
        assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
        command.fill('hostname')
        page.get_by_role('button', name='Executar', exact=True).click()
        expect(output).to_contain_text('computador-1')
        expect(faixa).to_contain_text('1 de 3 etapas')
        expect(faixa).to_contain_text('Consulte o endereço IPv4')
        command.fill('ip addr show eth0')
        page.get_by_role('button', name='Executar', exact=True).click()
        expect(output).to_contain_text('10.0.0.20/24')
        expect(faixa).to_contain_text('2 de 3 etapas')
        expect(faixa).to_contain_text('Teste a comunicação')
        page.get_by_role('button', name='Exibir saída longa', exact=True).click()
        expect(output).to_contain_text('Linha demonstrativa 32')
        command.fill('rascunho durante resize')
        page.set_viewport_size({'width': max(1050, width - 170), 'height': height})
        expect(command).to_have_value('rascunho durante resize')
        expect(output).to_contain_text('Linha demonstrativa 32')
        page.set_viewport_size({'width': width, 'height': height})
        page.locator('.lab-topologia button').filter(has_text='Computador 2').click()
        expect(page.locator('.lab-terminal-cabecalho')).to_contain_text('Computador 2')
        command.fill('rascunho PC2')
        page.set_viewport_size({'width': max(1050, width - 130), 'height': height})
        expect(page.locator('.lab-terminal-cabecalho')).to_contain_text('Computador 2')
        expect(command).to_have_value('rascunho PC2')
        page.set_viewport_size({'width': width, 'height': height})
        page.locator('.lab-topologia button').filter(has_text='Computador 1').click()
        expect(command).to_have_value('rascunho durante resize')
        expect(output).to_contain_text('Linha demonstrativa 32')
        page.get_by_role('button', name='Modo foco', exact=True).click()
        expect(command).to_have_value('rascunho durante resize')
        expect(page.locator('.sidebar')).not_to_be_visible()
        expect(page.locator('.topbar')).not_to_be_visible()
        assert output.bounding_box()['height'] >= 200
        box = command.bounding_box()
        assert box['y'] >= 0 and box['y'] + box['height'] <= height, ('Campo fora da área útil no modo foco', box, height)
        page.screenshot(path=str(report.with_suffix(f'.foco-{width}x{height}.png')), full_page=True)
        page.get_by_role('button', name='Sair do modo foco', exact=True).click()
        expect(page.locator('.topbar')).to_be_visible()
        page.get_by_role('radio', name='Sim, estão conectados à mesma rede.', exact=True).check()
        page.get_by_role('button', name='Registrar minha previsão', exact=True).click()
        expect(page.get_by_role('heading', name='Etapa 4: pratique e observe', exact=True)).to_be_visible()
        command.fill('ping -c 2 10.0.0.21')
        page.get_by_role('button', name='Executar', exact=True).click()
        expect(faixa).to_contain_text('3 de 3 etapas')
        expect(faixa).to_contain_text('Demonstração concluída')
        expect(faixa).to_contain_text('0 XP')
        expect(page.get_by_role('progressbar', name='Progresso da missão')).to_have_attribute('aria-valuenow', '100')
        expect(command).to_be_in_viewport(ratio=1)
        expect(page.get_by_role('button', name='Executar', exact=True)).to_be_in_viewport(ratio=1)
        page.locator('.lab-previa').screenshot(path=str(report.with_suffix(f'.{width}x{height}.png')))
        results.append({'viewport': [width, height], 'zoom': 1, 'terminal_output_height': round(output.bounding_box()['height']), 'ok': True})
        context.close()
    assert not errors, errors
    assert not [r for r in blocked if r['method'] != 'GET'], blocked
    browser.close()
report.write_text(json.dumps({'results': results, 'errors': errors, 'other_api_calls': blocked, 'modo': 'UI real + dados demonstrativos, auth interceptada'}, ensure_ascii=False, indent=2))
print(json.dumps({'ok': True, 'results': results, 'report': str(report)}, ensure_ascii=False))
